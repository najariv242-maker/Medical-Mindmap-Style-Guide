def get_pediatric_catalog_summary(domain: Optional[str] = None) -> str:
    """خلاصه دسته‌بندی‌شده مباحث رفرنس برای نمایش به کاربر یا استفاده در پرامپت هوش مصنوعی."""
    lines: List[str] = []
    if domain and domain in PEDIATRIC_CLINICAL_CATALOG:
        topics = PEDIATRIC_CLINICAL_CATALOG[domain]
        lines.append(f"📌 <b>{domain}</b> ({len(topics)} مبحث):")
        for i, t in enumerate(topics, 1):
            lines.append(f"  {i}. {t}")
        return "\n".join(lines)

    total_count = sum(len(items) for items in PEDIATRIC_CLINICAL_CATALOG.values())
    lines.append(f"📚 <b>فهرست جامع ۱۶۰ مبحث رفرنس نقشه ذهنی پزشکی (بخش اطفال):</b>\n")
    for d_name, d_topics in PEDIATRIC_CLINICAL_CATALOG.items():
        lines.append(f"▫️ <b>{d_name}</b> ({len(d_topics)} مبحث)")
        sample_topics = "، ".join(d_topics[:5])
        if len(d_topics) > 5:
            sample_topics += f" و {len(d_topics)-5} مورد دیگر…"
        lines.append(f"   <i>نمونه‌ها: {sample_topics}</i>\n")
    lines.append(f"✨ جمع کل مباحث رفرنس استاندارد: <b>{total_count} مبحث</b>")
    return "\n".join(lines)


def find_topic_archetype(topic_name: str) -> Tuple[str, Optional[str]]:
    """
    تشخیص هوشمند بهترین الگوی بالینی (از ۱۰ الگوی استاندارد) بر اساس نام مبحث یا واژه‌های کلیدی آن.
    خروجی: (template_mode, detected_domain)
    """
    cleaned = (topic_name or "").strip().lower()

    if any(k in cleaned for k in ("مراحل", "طبقه بندی", "طبقه‌بندی", "درجات", "گرید", "استیج", "stage", "grade", "انسفالوپاتی")):
        return "staging", None
    if any(k in cleaned for k in ("هیپرکالمی", "هایپوکالمی", "هایپوناترمی", "هایپوکلسمی", "الکترولیت", "اسیدوز", "آلکالوز", "کتواسیدوز", "dka")):
        return "electrolyte", None
    if any(k in cleaned for k in ("درمان حملات", "درمان دارویی", "آنتی هیستامین", "واکسیناسیون", "واکنش های انتقال خون")):
        return "pharma", None
    if any(k in cleaned for k in ("افتراق", "تفاوت", "مقایسه", "vs", "versus")):
        return "compare", None
    if any(k in cleaned for k in ("اپروچ", "احیا", "الگوریتم", "فلوچارت", "اقدامات فوری")):
        return "approach", None
    if any(k in cleaned for k in ("اتیولوژی", "انواع آنمی", "انواع سردرد", "علل", "ddx", "تشخیص افتراقی")):
        return "etiology", None
    if any(k in cleaned for k in ("ارزیابی های", "وورک", "اقدامات پاراکلینیک", "مطالعات تشخیصی", "تروما", "علائم هشدار")):
        return "workup", None
    if any(k in cleaned for k in ("اختلالات", "بیماری های", "سندرم های", "گروه")):
        return "multidisorder", None
    if any(k in cleaned for k in ("معاینه", "اعصاب کرانیال", "آناتومی", "غربالگری")):
        return "exam", None

    for domain_name, topics in PEDIATRIC_CLINICAL_CATALOG.items():
        for t in topics:
            if t.lower() in cleaned or cleaned in t.lower():
                if "اتیولوژی" in t or "انواع" in t or "علل" in t:
                    return "etiology", domain_name
                if "اپروچ" in t or "احیا" in t or "الگوریتم" in t:
                    return "approach", domain_name
                if "ارزیابی" in t:
                    return "workup", domain_name
                if "معاینه" in t:
                    return "exam", domain_name
                if "طبقه بندی" in t or "مراحل" in t:
                    return "staging", domain_name
                if "درمان" in t or "واکسیناسیون" in t:
                    return "pharma", domain_name
                if "افتراق" in t:
                    return "compare", domain_name
                return "disease", domain_name

    return "disease", None


