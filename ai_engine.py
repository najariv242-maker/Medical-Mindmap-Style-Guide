def _extract_gemini_text(resp_json: Dict[str, Any]) -> Optional[str]:
    candidates = resp_json.get("candidates")
    if isinstance(candidates, list) and candidates:
        content = candidates[0].get("content", {})
        parts = content.get("parts", [])
        # نادیده گرفتن پارت‌های thought در مدل‌های Thinking و استخراج فقط متن نهایی
        texts = [
            p.get("text", "")
            for p in parts
            if isinstance(p, dict) and p.get("text") and not p.get("thought")
        ]
        if not texts:
            texts = [p.get("text", "") for p in parts if isinstance(p, dict) and p.get("text")]
        if texts:
            return "\n".join(texts).strip()
    if isinstance(resp_json.get("output_text"), str) and resp_json["output_text"].strip():
        return resp_json["output_text"].strip()
    return None


def _single_rest_attempt(
    route_kind: str,
    model_name: str,
    api_key: str,
    system_prompt: str,
    user_prompt: str,
    use_header_auth: bool = False,
    timeout_sec: float = 24.0,
) -> str:
    """
    اجرای یک درخواست HTTP منفرد با تایم‌اوت کنترل‌شده به یکی از درگاه‌های رسمی Google (Google AI Studio یا Vertex).
    """
    encoded_key = urllib.parse.quote(api_key, safe="")
    headers: Dict[str, str] = {"Content-Type": "application/json"}

    if route_kind == "vertex_v1":
        base_url = f"https://aiplatform.googleapis.com/v1/publishers/google/models/{model_name}:generateContent"
    elif route_kind == "vertex_v1beta1":
        base_url = f"https://aiplatform.googleapis.com/v1beta1/publishers/google/models/{model_name}:generateContent"
    else:
        base_url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent"

    if use_header_auth:
        url = base_url
        headers["x-goog-api-key"] = api_key
    else:
        url = f"{base_url}?key={encoded_key}"

    gen_cfg: Dict[str, Any] = {
        "temperature": 0.2,
        "maxOutputTokens": 4096,
    }

    payload_dict = {
        "systemInstruction": {
            "parts": [{"text": system_prompt}]
        },
        "contents": [
            {
                "role": "user",
                "parts": [{"text": user_prompt}],
            }
        ],
        "generationConfig": gen_cfg,
    }
    payload_bytes = json.dumps(payload_dict, ensure_ascii=False).encode("utf-8")

    req = urllib.request.Request(url, data=payload_bytes, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout_sec) as response:
            raw_body = response.read().decode("utf-8", errors="replace")
            data = json.loads(raw_body)
            extracted = _extract_gemini_text(data)
            if extracted and len(extracted.strip()) > 5:
                return extracted.strip()
            raise RuntimeError(f"Empty response from {route_kind}/{model_name}")
    except urllib.error.HTTPError as http_err:
        err_body = ""
        try:
            err_body = http_err.read().decode("utf-8", errors="replace")[:220]
        except Exception:
            pass
        raise RuntimeError(f"{route_kind}({model_name}) HTTP {http_err.code}: {err_body}") from http_err


def _sync_call_google_endpoints(
    api_key: str,
    system_prompt: str,
    user_prompt: str,
    preferred_model: str,
    timeout_sec: float = 25.0,
) -> str:
    """
    موتور فوق‌سریع موازی (Parallel Hedged Request Engine):
    - درخواست‌ها را به صورت هم‌زمان به درگاه رسمی Google AI Studio با مدل انتخابی (gemini-flash-latest)
      و مدل‌های پرسرعت جایگزین ارسال می‌کند.
    - اولین پاسخی که در سریع‌ترین زمان بازگردد برنده شده و در کش ذخیره می‌شود.
    """
    global _WINNING_ROUTE_CACHE

    # ۱. اگر از درخواست قبلی مسیر برنده‌ای در کش داریم، ابتدا همان را امتحان کن
    if _WINNING_ROUTE_CACHE is not None:
        c_route, c_model, c_hdr = _WINNING_ROUTE_CACHE
        try:
            res = _single_rest_attempt(
                route_kind=c_route,
                model_name=c_model,
                api_key=api_key,
                system_prompt=system_prompt,
                user_prompt=user_prompt,
                use_header_auth=c_hdr,
                timeout_sec=16.0,
            )
            logger.info("Fast cache hit on %s (%s)", c_route, c_model)
            return res
        except Exception as cache_exc:
            logger.warning("Cached route %s/%s failed (%s); falling back to parallel race.", c_route, c_model, cache_exc)
            _WINNING_ROUTE_CACHE = None

    # ۲. چینش هوشمند کاندیداها بر اساس مدل انتخابی کاربر
    pref = (preferred_model or "gemini-flash-latest").strip()
    primary_models: List[str] = [pref]
    for m in (
        "gemini-flash-latest",
        "gemini-flash-lite-latest",
        "gemini-3.7-flash",
        "gemini-3.8-flash",
        "gemini-3.6-flash",
        "gemini-3.5-flash",
        "gemini-3.5-flash-lite",
        "gemini-3.1-flash-lite",
    ):
        if m not in primary_models:
            primary_models.append(m)

    # موج ۱: مدل درخواستی (gemini-flash-latest) و مدل‌های سریع فلش در Google AI Studio
    wave_1_candidates: List[Tuple[str, str, bool]] = [
        ("aistudio_v1beta", primary_models[0], False),
        ("aistudio_v1beta", "gemini-flash-lite-latest", False),
        ("aistudio_v1beta", primary_models[0], True),
    ]
    if len(primary_models) > 1 and primary_models[1] not in ("gemini-flash-latest", "gemini-flash-lite-latest"):
        wave_1_candidates.append(("aistudio_v1beta", primary_models[1], False))
    wave_1_candidates.append(("aistudio_v1beta", "gemini-3.7-flash", False))

    # موج ۲: مدل‌های پشتیبان ثانویه و درگاه‌های موازی
    wave_2_candidates: List[Tuple[str, str, bool]] = [
        ("aistudio_v1beta", "gemini-3.8-flash", False),
        ("aistudio_v1beta", "gemini-3.6-flash", False),
        ("aistudio_v1beta", "gemini-3.5-flash", False),
        ("aistudio_v1beta", "gemini-3.5-flash-lite", False),
        ("vertex_v1", primary_models[0], False),
        ("vertex_v1beta1", primary_models[0], False),
    ]

    errors_collected: List[str] = []

    for wave_idx, candidates in enumerate((wave_1_candidates, wave_2_candidates), start=1):
        pool = concurrent.futures.ThreadPoolExecutor(max_workers=len(candidates))
        future_to_cfg = {
            pool.submit(
                _single_rest_attempt,
                cfg[0],
                cfg[1],
                api_key,
                system_prompt,
                user_prompt,
                cfg[2],
                timeout_sec,
            ): cfg
            for cfg in candidates
        }
        try:
            for fut in concurrent.futures.as_completed(future_to_cfg, timeout=timeout_sec + 4.0):
                cfg = future_to_cfg[fut]
                try:
                    result_text = fut.result()
                    if result_text:
                        _WINNING_ROUTE_CACHE = cfg
                        logger.info(
                            "Wave %d winner: route=%s model=%s header=%s",
                            wave_idx, cfg[0], cfg[1], cfg[2]
                        )
                        pool.shutdown(wait=False, cancel_futures=True)
                        return result_text
                except Exception as exc:
                    errors_collected.append(str(exc))
        except concurrent.futures.TimeoutError:
            errors_collected.append(f"Wave {wave_idx} timed out after {timeout_sec}s")
        finally:
            pool.shutdown(wait=False, cancel_futures=True)

    # بررسی خطاهای احراز هویت
    unique_errors = []
    has_auth_error = False
    for e in errors_collected:
        if e not in unique_errors:
            unique_errors.append(e)
        if ("API key not valid" in e or "API_KEY_INVALID" in e or "UNAUTHENTICATED" in e) and "403" not in e:
            has_auth_error = True

    if has_auth_error:
        raise RuntimeError(
            "کلید API هوش مصنوعی نامعتبر است (API key not valid).\n\n"
            "🔑 نحوه حل مشکل:\n"
            "1. به سایت Google AI Studio (https://aistudio.google.com/app/apikey) مراجعه کنید.\n"
            "2. کلید اختصاصی خود را بسازید (کلیدهایی با پیشوند AQ. یا AIza).\n"
            "3. کلید را در فایل .env در متغیر AI_API_KEY قرار دهید یا با دستور /setkey در ربات ارسال کنید."
        )

    error_summary = " | ".join(unique_errors[:3]) if unique_errors else "Unknown connection error"
    raise RuntimeError(f"خطا در ارتباط با وب‌سرویس هوش مصنوعی: {error_summary}")


def _sync_call_openai_compatible(
    api_key: str,
    base_url: str,
    system_prompt: str,
    user_prompt: str,
    model_name: str,
    timeout_sec: float = 45.0,
) -> str:
    url = base_url.rstrip("/") + "/chat/completions"
    candidate_models: List[str] = []
    if "codecraftapi.com" in base_url or api_key.startswith("cc_"):
        # اولویت با مدل‌های سبک/رایگان و سپس مدل‌های Flash در CodeCraft
        for m in (model_name, "gemma-2-2b", "deepseek-v4-flash-0731", "gpt-5.6-luna", "gemini-3.7-flash", "gemini-3.6-flash"):
            if m and m not in candidate_models:
                candidate_models.append(m)
    else:
        candidate_models.append(model_name or "gpt-4o-mini")

    last_error = ""
    for current_model in candidate_models:
        payload = {
            "model": current_model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            "temperature": 0.2,
            "max_tokens": 4096,
        }
        req = urllib.request.Request(
            url,
            data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
            headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {api_key}",
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko)",
            },
            method="POST",
        )
        try:
            with urllib.request.urlopen(req, timeout=timeout_sec) as response:
                data = json.loads(response.read().decode("utf-8", errors="replace"))
                msg = data.get("choices", [{}])[0].get("message", {})
                content = msg.get("content")
                if not content and "reasoning_content" in msg:
                    content = msg.get("reasoning_content")
                if content and content.strip():
                    return content.strip()
                last_error = f"پاسخ خالی از سرور مدل ({current_model}) دریافت شد."
        except urllib.error.HTTPError as http_err:
            err_body = ""
            try:
                err_body = http_err.read().decode("utf-8", errors="replace")[:250]
            except Exception:
                pass
            last_error = f"CodeCraft/OpenAI API HTTP {http_err.code} ({current_model}): {err_body}"
            # اگر خطای 401 یا 402 (Billing verification failed / insufficient_quota) رخ داد، کلید را علامت‌گذاری کن تا بلافاصله به موتور رایگان سوییچ شود
            if http_err.code in (401, 402, 403):
                _BILLING_FAILED_KEYS.add(api_key)
                break
        except Exception as exc:
            last_error = f"خطا در مدل {current_model}: {exc}"

    raise RuntimeError(last_error or "خطا در ارتباط با سرور OpenAI/CodeCraft.")


def _single_pollinations_attempt(
    endpoint_url: str,
    model_name: str,
    system_prompt: str,
    user_prompt: str,
    timeout_sec: float = 45.0,
) -> str:
    """
    فراخوانی موتور رایگان و بدون نیاز به کلید/کارت بانکی (Pollinations OpenAI-Compatible API).
    """
    payload = {
        "model": model_name,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
        "temperature": 0.2,
        "private": True,
    }
    req = urllib.request.Request(
        endpoint_url,
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "Accept": "application/json",
            "Authorization": "Bearer dummy-free-key",
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko)",
        },
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=timeout_sec) as response:
        raw_body = response.read().decode("utf-8", errors="replace").strip()
        if not raw_body:
            raise RuntimeError(f"Empty body from {endpoint_url} ({model_name})")
        if raw_body.startswith("{"):
            try:
                data = json.loads(raw_body)
                if isinstance(data, dict) and "choices" in data and data["choices"]:
                    msg = data["choices"][0].get("message", {})
                    content = msg.get("content") or msg.get("reasoning_content") or ""
                    if content and content.strip():
                        return content.strip()
            except Exception:
                pass
        if "#" in raw_body and ("##" in raw_body or "-" in raw_body):
            return raw_body
        raise RuntimeError(f"Unexpected response format from {endpoint_url} ({model_name})")


def _sync_call_free_cloud_fallbacks(
    system_prompt: str,
    user_prompt: str,
    timeout_sec: float = 50.0,
) -> str:
    """
    موتور موازی رایگان (بدون نیاز به کارت بانکی یا تایید Billing) برای مواقعی که کلید CodeCraft خطای 402 می‌دهد.
    """
    candidates = [
        ("https://text.pollinations.ai/openai", "openai"),
        ("https://text.pollinations.ai/openai", "gemini"),
        ("https://text.pollinations.ai/openai", "deepseek"),
        ("https://text.pollinations.ai/openai/chat/completions", "openai"),
        ("https://text.pollinations.ai/", "openai"),
        ("https://text.pollinations.ai/", "mistral"),
    ]
    pool = concurrent.futures.ThreadPoolExecutor(max_workers=len(candidates))
    future_to_cfg = {
        pool.submit(
            _single_pollinations_attempt,
            ep,
            mdl,
            system_prompt,
            user_prompt,
            timeout_sec,
        ): (ep, mdl)
        for ep, mdl in candidates
    }
    errors: List[str] = []
    try:
        for fut in concurrent.futures.as_completed(future_to_cfg, timeout=timeout_sec + 5.0):
            ep, mdl = future_to_cfg[fut]
            try:
                res = fut.result()
                if res and len(res.strip()) > 10:
                    logger.info("Free cloud AI fallback succeeded via %s (%s)", ep, mdl)
                    pool.shutdown(wait=False, cancel_futures=True)
                    return res.strip()
            except Exception as exc:
                errors.append(f"{mdl}: {exc}")
    except concurrent.futures.TimeoutError:
        errors.append("Free cloud fallback timed out")
    finally:
        pool.shutdown(wait=False, cancel_futures=True)

    raise RuntimeError(" | ".join(errors[:3]) if errors else "Free cloud fallback failed")


